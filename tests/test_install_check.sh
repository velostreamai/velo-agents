#!/usr/bin/env bash
# Pins #2091: __pycache__ and *.pyc are PYTHON RUNTIME ARTIFACTS, not tooling.
#
# python creates __pycache__/*.pyc wherever it imports a module — including
# .agents/bin (velo_worker_runner imports velo_runner_lib). install.sh used to
# copy those into the live tree and then --check compare them, but a .pyc embeds
# the source's mtime, so every python run regenerated them and --check reported
# drift that no install could ever fix. A drift check that always fires trains
# everyone to ignore the one signal that catches a genuinely stale live copy.
# Each check below names the failure it prevents.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REAL="$HERE/../install.sh"
RC=0
FAKE=$(mktemp -d)
trap 'rm -rf "$FAKE"' EXIT

check() {  # name, got, want-substring
  if [[ "$2" == *"$3"* ]]; then echo "  PASS  $1"
  else echo "  FAIL  $1: got '$2', want to contain '$3'"; RC=1; fi
}
check_exit() {  # name, got, want
  if [[ "$2" == "$3" ]]; then echo "  PASS  $1"
  else echo "  FAIL  $1: exit $2, want $3"; RC=1; fi
}
deny() {  # name, got — PASSes when got is empty
  if [[ -z "$2" ]]; then echo "  PASS  $1"
  else echo "  FAIL  $1: got '$2'"; RC=1; fi
}
reject() {  # name, got, forbidden-substring
  if [[ "$2" != *"$3"* ]]; then echo "  PASS  $1"
  else echo "  FAIL  $1: got '$2', must not contain '$3'"; RC=1; fi
}

# install.sh derives SRC from its own location, so the unmodified real script is
# copied into a throwaway source tree carrying the artifacts python leaves behind.
SRC="$FAKE/src"
DEST="$FAKE/live-agents"
SKILLS="$FAKE/claude-skills"
mkdir -p "$SRC/bin/__pycache__" "$SRC/rules"
cp "$REAL" "$SRC/install.sh"
echo 'echo dispatch'  > "$SRC/bin/velo-dispatch"
echo '# runner lib'   > "$SRC/bin/velo_runner_lib.py"
echo 'old bytecode'   > "$SRC/bin/__pycache__/velo_runner_lib.cpython-314.pyc"
echo 'rule text'      > "$SRC/rules/policy.md"

# ── fresh install ─────────────────────────────────────────────────────────────
VELO_AGENTS_HOME="$DEST" VELO_CLAUDE_SKILLS="$SKILLS" bash "$SRC/install.sh" \
  > "$FAKE/install.out" 2>&1
check "install succeeds" "$(cat "$FAKE/install.out")" "installed"

# Prevents: python artifacts being shipped as if they were tooling — the defect
# that put .pyc files into ~/.agents in the first place.
deny "fresh install ships no .pyc files" \
  "$(find "$DEST" -name '*.pyc' -print)"
deny "fresh install ships no __pycache__ directories" \
  "$(find "$DEST" -type d -name __pycache__ -print)"

# ── --check after python has run against both trees ───────────────────────────
# Running the installed runner creates __pycache__ next to BOTH copies, and the
# two .pyc files never match (a .pyc embeds the source mtime). Prevents:
# --check reporting permanent drift no install can fix, teaching everyone to
# ignore the one signal that catches a genuinely stale live copy.
mkdir -p "$DEST/bin/__pycache__"
echo 'bytecode regenerated by the live run' > "$DEST/bin/__pycache__/velo_runner_lib.cpython-314.pyc"
echo 'bytecode regenerated by the repo run' > "$SRC/bin/__pycache__/velo_runner_lib.cpython-314.pyc"
VELO_AGENTS_HOME="$DEST" VELO_CLAUDE_SKILLS="$SKILLS" bash "$SRC/install.sh" --check \
  > "$FAKE/check.out" 2>&1
check_exit "--check exits 0 when only python artifacts differ" "$?" "0"
reject "--check never mentions python artifacts" "$(cat "$FAKE/check.out")" "pyc"

# ── --check still catches a REAL difference ───────────────────────────────────
# Prevents: the artifact exclusion weakening the check into accepting a
# genuinely stale live copy — the drift it exists to report in the first place.
echo 'echo LIVE EDIT' >> "$DEST/bin/velo-dispatch"
VELO_AGENTS_HOME="$DEST" VELO_CLAUDE_SKILLS="$SKILLS" bash "$SRC/install.sh" --check \
  > "$FAKE/drift.out" 2>&1
check_exit "a real live edit still fails --check" "$?" "1"
check "the failing --check names the edited file" "$(cat "$FAKE/drift.out")" "bin/velo-dispatch"

# ── update.sh: python artifacts in the live copy are not pulled back into the checkout ──
# update.sh copies the live tree back so a live fix can be committed. A .pyc in the live bin/ (python writes one wherever it
# imports) is not tooling. Prevents: the walk of the LIVE tree forgetting the exclusion install.sh's walks have, which would
# report every bytecode file as new work to commit and copy it into the checkout.
UPSRC="$FAKE/up-src"
UPLIVE="$FAKE/up-live"
mkdir -p "$UPSRC/bin" "$UPLIVE/bin/__pycache__"
cp "$HERE/../update.sh" "$UPSRC/update.sh"
echo 'echo dispatch'      > "$UPSRC/bin/velo-dispatch"
echo 'echo dispatch LIVE' > "$UPLIVE/bin/velo-dispatch"   # a live edit: it must come back
echo 'echo new tool'      > "$UPLIVE/bin/velo-newtool"    # a file only the live copy has: it must come back too
echo 'live bytecode'      > "$UPLIVE/bin/__pycache__/velo_runner_lib.cpython-314.pyc"
echo 'stray bytecode'     > "$UPLIVE/bin/old_module.pyc"
VELO_AGENTS_HOME="$UPLIVE" bash "$UPSRC/update.sh" > "$FAKE/update.out" 2>&1
check_exit "update.sh succeeds" "$?" "0"
check "update.sh copies a live edit back (control: it does copy)" "$(cat "$UPSRC/bin/velo-dispatch")" "LIVE"
check "update.sh copies a file only the live copy has (control)" "$(cat "$UPSRC/bin/velo-newtool" 2>&1)" "new tool"
deny "update.sh copies no .pyc file back" "$(find "$UPSRC" -name '*.pyc' -print)"
deny "update.sh copies no __pycache__ directory back" "$(find "$UPSRC" -type d -name __pycache__ -print)"
reject "update.sh never mentions python artifacts" "$(cat "$FAKE/update.out")" "pyc"

echo
[[ $RC -eq 0 ]] && echo "all install-check tests passed" || echo "FAILED"
exit $RC
